CREATE TABLE account_locks (
    account_id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    event_cursor BIGINT NOT NULL DEFAULT 0,
    FOREIGN KEY(account_id,user_id) REFERENCES dakia_control.accounts(id,user_id) ON DELETE CASCADE
);
CREATE TABLE drafts (
    account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
    id TEXT NOT NULL,
    revision BIGINT NOT NULL,
    document TEXT NOT NULL,
    PRIMARY KEY(account_id,id)
);
CREATE TABLE blobs (
    account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
    id TEXT NOT NULL,
    size_bytes BIGINT NOT NULL,
    pinned BIGINT NOT NULL CHECK(pinned IN (0,1)),
    last_access TEXT NOT NULL,
    PRIMARY KEY(account_id,id)
);
CREATE TABLE draft_blobs (
    account_id TEXT NOT NULL,
    draft_id TEXT NOT NULL,
    blob_id TEXT NOT NULL,
    PRIMARY KEY(account_id,draft_id,blob_id),
    FOREIGN KEY(account_id,draft_id) REFERENCES drafts(account_id,id) ON DELETE CASCADE,
    FOREIGN KEY(account_id,blob_id) REFERENCES blobs(account_id,id)
);
CREATE TABLE attachment_metadata (
    account_id TEXT NOT NULL,
    id TEXT NOT NULL,
    document TEXT NOT NULL,
    PRIMARY KEY(account_id,id),
    FOREIGN KEY(account_id,id) REFERENCES blobs(account_id,id) ON DELETE CASCADE
);
CREATE TABLE submissions (
    account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
    id TEXT NOT NULL,
    operation_id TEXT NOT NULL,
    request TEXT NOT NULL,
    draft_id TEXT NOT NULL,
    draft_revision BIGINT NOT NULL,
    snapshot TEXT NOT NULL,
    document TEXT NOT NULL,
    state TEXT NOT NULL,
    due_at TEXT NOT NULL,
    lease_until TEXT,
    filing_status TEXT NOT NULL,
    scheduled_by_user BIGINT NOT NULL DEFAULT 0 CHECK(scheduled_by_user IN (0,1)),
    PRIMARY KEY(account_id,id),
    UNIQUE(account_id,operation_id)
);
CREATE INDEX submissions_due ON submissions(account_id,state,due_at,id);
CREATE INDEX submissions_scheduled ON submissions(account_id,scheduled_by_user,due_at,id);
CREATE TABLE outbox (
    account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kind TEXT NOT NULL,
    target_id TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending',
    lease_until TEXT,
    PRIMARY KEY(account_id,id),
    UNIQUE(account_id,kind,target_id)
);
CREATE TABLE events (
    account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
    cursor BIGINT NOT NULL,
    revision BIGINT NOT NULL,
    kind TEXT NOT NULL,
    target_id TEXT NOT NULL,
    PRIMARY KEY(account_id,cursor)
);
CREATE TABLE submission_mime (
    account_id TEXT NOT NULL,
    submission_id TEXT NOT NULL,
    raw BYTEA NOT NULL,
    recipients TEXT NOT NULL,
    message_id TEXT NOT NULL,
    PRIMARY KEY(account_id,submission_id),
    FOREIGN KEY(account_id,submission_id) REFERENCES submissions(account_id,id) ON DELETE CASCADE
);
CREATE TABLE provider_documents (
    account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
    key TEXT NOT NULL,
    document TEXT NOT NULL,
    PRIMARY KEY(account_id,key)
);
CREATE INDEX provider_document_prefix ON provider_documents(account_id,key COLLATE "C");
