CREATE FUNCTION mail_folders(document TEXT) RETURNS TEXT[] LANGUAGE SQL IMMUTABLE STRICT SET search_path=dakia_mail,pg_catalog AS $$
 SELECT COALESCE(array_agg(value),ARRAY[]::TEXT[]) FROM jsonb_array_elements_text(document::jsonb->'folder_ids') value
$$;
CREATE FUNCTION mail_reference(document TEXT) RETURNS JSONB LANGUAGE plpgsql IMMUTABLE STRICT SET search_path=dakia_mail,pg_catalog AS $$
BEGIN RETURN (document::jsonb->>'provider_id')::jsonb;
EXCEPTION WHEN invalid_text_representation THEN RETURN NULL;
END $$;
CREATE TABLE messages (
 account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
 id TEXT NOT NULL,revision BIGINT NOT NULL,document TEXT NOT NULL,category_override TEXT,
 source TEXT GENERATED ALWAYS AS (document::jsonb->>'provider_id') STORED,
 folder_ids TEXT[] GENERATED ALWAYS AS (mail_folders(document)) STORED,
 received_at TEXT GENERATED ALWAYS AS (document::jsonb->>'received_at') STORED,
 sender_email TEXT GENERATED ALWAYS AS (lower(document::jsonb->'sender'->>'email')) STORED,
 thread_id TEXT GENERATED ALWAYS AS (document::jsonb->>'thread_id') STORED,
 unread BOOLEAN GENERATED ALWAYS AS ((document::jsonb->>'unread')::BOOLEAN) STORED,
 starred BOOLEAN GENERATED ALWAYS AS ((document::jsonb->>'starred')::BOOLEAN) STORED,
 category TEXT GENERATED ALWAYS AS (document::jsonb->>'category') STORED,
 category_status TEXT GENERATED ALWAYS AS (document::jsonb->>'category_status') STORED,
 provider_folder TEXT GENERATED ALWAYS AS (mail_reference(document)->>'folder') STORED,
 provider_epoch BIGINT GENERATED ALWAYS AS ((mail_reference(document)->>'uidvalidity')::BIGINT) STORED,
 PRIMARY KEY(account_id,id)
);
