-- Tombstones survive message deletion. The clock belongs to the account, so
-- independently queued changes can be replayed with a stable source version.
ALTER TABLE account_locks ADD COLUMN search_sequence BIGINT NOT NULL DEFAULT 0;
CREATE TABLE search_index_outbox (
 account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
 message_id TEXT NOT NULL,sequence BIGINT NOT NULL,PRIMARY KEY(account_id,message_id)
);
CREATE INDEX search_index_outbox_order ON search_index_outbox(account_id,sequence);
CREATE FUNCTION publish_search_change(owner_account TEXT,message TEXT) RETURNS VOID LANGUAGE plpgsql SET search_path=dakia_mail,pg_catalog AS $$
DECLARE next_sequence BIGINT;
BEGIN
 UPDATE account_locks SET search_sequence=search_sequence+1 WHERE account_id=owner_account RETURNING search_sequence INTO next_sequence;
 IF next_sequence IS NOT NULL THEN
  INSERT INTO search_index_outbox(account_id,message_id,sequence) VALUES(owner_account,message,next_sequence)
   ON CONFLICT(account_id,message_id) DO UPDATE SET sequence=excluded.sequence;
 END IF;
END $$;
CREATE FUNCTION mailbox_search_change() RETURNS TRIGGER LANGUAGE plpgsql SET search_path=dakia_mail,pg_catalog AS $$
BEGIN
 IF TG_OP='DELETE' THEN
  PERFORM publish_search_change(OLD.account_id,OLD.id);
  RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' AND OLD.document=NEW.document THEN RETURN NEW; END IF;
 INSERT INTO search_dirty(account_id,message_id) VALUES(NEW.account_id,NEW.id) ON CONFLICT DO NOTHING;
 PERFORM publish_search_change(NEW.account_id,NEW.id);
 RETURN NEW;
END $$;
CREATE TRIGGER mailbox_search_insert AFTER INSERT ON messages FOR EACH ROW EXECUTE FUNCTION mailbox_search_change();
CREATE TRIGGER mailbox_search_update AFTER UPDATE OF document ON messages FOR EACH ROW EXECUTE FUNCTION mailbox_search_change();
CREATE TRIGGER mailbox_search_delete AFTER DELETE ON messages FOR EACH ROW EXECUTE FUNCTION mailbox_search_change();
CREATE FUNCTION mailbox_dirty_reconciled() RETURNS TRIGGER LANGUAGE plpgsql SET search_path=dakia_mail,pg_catalog AS $$
BEGIN PERFORM publish_search_change(OLD.account_id,OLD.message_id); RETURN OLD; END $$;
CREATE TRIGGER mailbox_search_reconciled AFTER DELETE ON search_dirty FOR EACH ROW EXECUTE FUNCTION mailbox_dirty_reconciled();
