import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { DakiaProvider } from "@dakia/ui";
import { AgentConnections, agentConnectionsApi } from "./AgentConnections";
beforeEach(() => { Object.defineProperty(Element.prototype, "scrollIntoView", { configurable: true, value: vi.fn() }); vi.stubGlobal("matchMedia", vi.fn(() => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() }))); });
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it("creates with both permissions off, shows token once, edits and revokes", async () => {
  const connection = { id: "fixture", name: "Research", allow_send: false, allow_delete: false, created_at: 0, revoked: false };
  vi.spyOn(agentConnectionsApi, "list").mockResolvedValue([]);
  const create = vi.spyOn(agentConnectionsApi, "create").mockResolvedValue({ connection, token: "synthetic-once" });
  const edit = vi.spyOn(agentConnectionsApi, "edit").mockResolvedValue({ ...connection, allow_send: true });
  const revoke = vi.spyOn(agentConnectionsApi, "revoke").mockResolvedValue(undefined);
  const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  render(<DakiaProvider><QueryClientProvider client={client}><AgentConnections userId="owner" /></QueryClientProvider></DakiaProvider>);
  await screen.findByText("No active connections.");
  expect(screen.getByRole("radio", { name: "ChatGPT" })).toHaveProperty("checked", true);
  expect(create).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("radio", { name: "Other AI agent" }));
  fireEvent.click(screen.getByRole("button", { name: "Use a token instead" }));
  fireEvent.change(screen.getByRole("textbox", { name: "Connection name" }), { target: { value: "Research" } });
  fireEvent.click(screen.getByRole("button", { name: "Create token" }));
  await waitFor(() => expect(create).toHaveBeenCalledWith("Research"));
  await screen.findByText("Authorization: Bearer synthetic-once");
  fireEvent.click(screen.getByRole("button", { name: "Close manual setup" }));
  expect(screen.queryByText("Authorization: Bearer synthetic-once")).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Edit Research" }));
  expect((screen.getByRole("checkbox", { name: "Allow sending" }) as HTMLInputElement).checked).toBe(false);
  expect((screen.getByRole("checkbox", { name: /Allow deleting/ }) as HTMLInputElement).checked).toBe(false);
  fireEvent.click(screen.getByRole("checkbox", { name: "Allow sending" }));
  fireEvent.click(screen.getByRole("button", { name: "Save changes" }));
  await waitFor(() => expect(edit).toHaveBeenCalledWith("fixture", { name: "Research", allow_send: true, allow_delete: false }));
  await waitFor(() => expect(screen.queryByRole("textbox", { name: "Connection name" })).toBeNull());
  fireEvent.click(screen.getByRole("button", { name: "Revoke Research" }));
  fireEvent.click(screen.getByRole("button", { name: "Revoke connection" }));
  await waitFor(() => expect(revoke.mock.calls.map(([id]) => id)).toEqual(["fixture"]));
  client.clear();
});
