CREATE TABLE model_jobs (
 account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
 id TEXT NOT NULL,queue_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 document TEXT NOT NULL,state TEXT NOT NULL,retry_count BIGINT NOT NULL DEFAULT 0,
 retry_at BIGINT NOT NULL DEFAULT 0,failure_reason TEXT,
 message_id TEXT GENERATED ALWAYS AS (document::jsonb->>'message_id') STORED,
 kind TEXT GENERATED ALWAYS AS (document::jsonb->>'kind') STORED,
 deadline TEXT GENERATED ALWAYS AS (document::jsonb->>'deadline') STORED,
 PRIMARY KEY(account_id,id)
);
CREATE INDEX model_jobs_active_message ON model_jobs(account_id,message_id) WHERE state IN ('pending','running');
CREATE INDEX model_jobs_due ON model_jobs(account_id,retry_at,queue_id) WHERE state='pending';
