CREATE TABLE folder_scans (
 account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
 folder TEXT NOT NULL,generation BIGINT NOT NULL DEFAULT 1,continuation TEXT,
 completed_at BIGINT,last_scanned_at BIGINT,initial_boundary BIGINT,uidvalidity BIGINT,
 coverage_limited BOOLEAN NOT NULL DEFAULT FALSE,PRIMARY KEY(account_id,folder)
);
CREATE TABLE folder_memberships (
 account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
 folder TEXT NOT NULL,message_id TEXT NOT NULL,generation BIGINT NOT NULL,
 PRIMARY KEY(account_id,folder,message_id)
);
CREATE INDEX folder_membership_generation ON folder_memberships(account_id,folder,generation,message_id);
CREATE TABLE notification_dedup (
 account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
 message_id TEXT NOT NULL,PRIMARY KEY(account_id,message_id)
);
CREATE TABLE push_jobs (
 account_id TEXT NOT NULL REFERENCES account_locks(account_id) ON DELETE CASCADE,
 id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 message_id TEXT NOT NULL,subscription_id TEXT NOT NULL,document TEXT NOT NULL,state TEXT NOT NULL,
 attempts BIGINT NOT NULL DEFAULT 0,next_attempt BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(account_id,message_id,subscription_id)
);
CREATE INDEX push_jobs_pending ON push_jobs(account_id,state,next_attempt,id);
CREATE FUNCTION mail_upper_folders(document TEXT) RETURNS TEXT[] LANGUAGE SQL IMMUTABLE STRICT SET search_path=dakia_mail,pg_catalog AS $$
 SELECT COALESCE(array_agg(upper(value)),ARRAY[]::TEXT[]) FROM jsonb_array_elements_text(document::jsonb->'folder_ids') value
$$;
ALTER TABLE messages ADD COLUMN upper_folders TEXT[] GENERATED ALWAYS AS (mail_upper_folders(document)) STORED;
CREATE INDEX messages_upper_folders ON messages USING GIN(upper_folders);
